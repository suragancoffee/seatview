const DKEY = { front:'f', mid:'m', back:'b' };
const EYE = 0.85;            // 의자 하단에서 앉은 눈높이

export function seatEye(zone, depth) {
  const [r, y] = SEAT_POS[zone][DKEY[depth]];
  const [x, z] = toModel(chartAngle(zone), r);
  return [x, y + EYE, z];
}
export function seatRange(zone) { const p = SEAT_POS[zone]; return [p.f[0], p.b[0]]; }

// 휠체어석: 좌석배치도의 장애인석 라인(5~11구역 뒤, 1층 맨 뒤 통로). 모델에서 통로 바닥 4.75m 측정
export const WHEELCHAIR = [
  { id:'w5', label:'5~6구역 뒤', deg:(chartAngle(5) + chartAngle(6)) / 2 },
  { id:'w8', label:'7~9구역 뒤', deg:chartAngle(8) },
  { id:'w11', label:'10~11구역 뒤', deg:(chartAngle(10) + chartAngle(11)) / 2 },
];
export function wheelchairEye(id) {
  const w = WHEELCHAIR.find(q => q.id === id), [x, z] = toModel(w.deg, 44.0);
  return [x, 4.75 + 1.25, z];   // 휠체어 앉은 눈높이 1.25m
}

