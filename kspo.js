const DKEY = { front:'f', mid:'m', back:'b' };
const EYE = 1.15;            // 좌석 단에서 앉은 눈높이

export function seatEye(zone, depth) {
  const [r, y] = SEAT_POS[zone][DKEY[depth]];
  const [x, z] = toModel(chartAngle(zone), r);
  return [x, y + EYE, z];
}
export function seatRange(zone) { const p = SEAT_POS[zone]; return [p.f[0], p.b[0]]; }

